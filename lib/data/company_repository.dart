import 'dart:convert';

import 'package:http/http.dart' as http;

import '../models/producer.dart';

abstract interface class CompanyRepository {
  Future<List<Producer>> getCompanies();
}

class ApiCompanyRepository implements CompanyRepository {
  final String baseUrl;
  final http.Client client;

  ApiCompanyRepository({required this.baseUrl, http.Client? client})
    : client = client ?? http.Client();

  @override
  Future<List<Producer>> getCompanies() async {
    final cleanBaseUrl = baseUrl.replaceFirst(RegExp(r'\/+$'), '');

    final uri = Uri.parse('$cleanBaseUrl/api/producers');

    print('======================================');
    print('GET COMPANIES');
    print('URL: $uri');
    print('======================================');

    try {
      final response = await client
          .get(uri, headers: {'Accept': 'application/json'})
          .timeout(const Duration(seconds: 20));

      print('======================================');
      print('RESPONSE RECEIVED');
      print('STATUS: ${response.statusCode}');
      print('BODY: ${response.body}');
      print('======================================');

      if (response.statusCode < 200 || response.statusCode >= 300) {
        throw Exception(
          'API returned ${response.statusCode}: ${response.body}',
        );
      }

      final decoded = jsonDecode(response.body);

      List<dynamic> list;

      if (decoded is List) {
        list = decoded;
      } else if (decoded is Map<String, dynamic>) {
        final data = decoded['data'];

        if (data is List) {
          list = data;
        } else {
          throw Exception('Expected "data" to be a list, but received: $data');
        }
      } else {
        throw Exception('Invalid API response format');
      }

      print('COMPANIES RECEIVED: ${list.length}');

      return list
          .map((item) => Producer.fromJson(Map<String, dynamic>.from(item)))
          .toList();
    } catch (e, stackTrace) {
      print('======================================');
      print('GET COMPANIES FAILED');
      print('ERROR: $e');
      print('STACK TRACE:');
      print(stackTrace);
      print('======================================');

      rethrow;
    }
  }
}

